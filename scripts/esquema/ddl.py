# Saca la estructura completa (public + harvey) de la base real a esquema_completo.sql y sentencias.json.
# Uso (en el entorno de Claude, con api.supabase.com conectado): cd scripts/esquema && python3 ddl.py
import sys; sys.path.insert(0,'.')
from api import q
S = "('public','harvey')"
out = []
w = out.append
w("-- Estructura completa de la base de FERJUSANZ (public + harvey), generada desde producción.\n-- No lleva datos. Generada por Claude el 12/11/2026.\nset check_function_bodies = off;\nset client_min_messages = warning;")
w("create extension if not exists pg_cron with schema pg_catalog;")
w("create schema if not exists harvey;")
# secuencias
for r in q(f"""select format('create sequence if not exists %I.%I as %s increment %s minvalue %s maxvalue %s start %s cache %s%s;', schemaname, sequencename, data_type, increment_by, min_value, max_value, start_value, cache_size, case when cycle then ' cycle' else '' end) s from pg_sequences where schemaname in {S}
  and not exists (select 1 from pg_depend dp join pg_class sc on sc.oid = dp.objid join pg_namespace sn on sn.oid = sc.relnamespace where sn.nspname = schemaname and sc.relname = sequencename and dp.deptype = 'i')  -- las de «identity» las crea su tabla; si no, salían dos
  order by 1"""):
    w(r["s"])
# tablas
cols = q(f"""select n.nspname s, c.relname t, a.attnum, format('%I %s', a.attname, format_type(a.atttypid,a.atttypmod))
 || case when a.attgenerated='s' then ' generated always as ('||pg_get_expr(d.adbin,d.adrelid)||') stored' else '' end
 || case when a.attidentity='a' then ' generated always as identity' when a.attidentity='d' then ' generated by default as identity' else '' end
 || case when d.adbin is not null and a.attgenerated<>'s' then ' default '||pg_get_expr(d.adbin,d.adrelid) else '' end
 || case when a.attnotnull then ' not null' else '' end as col
 from pg_class c join pg_namespace n on n.oid=c.relnamespace join pg_attribute a on a.attrelid=c.oid and a.attnum>0 and not a.attisdropped
 left join pg_attrdef d on d.adrelid=c.oid and d.adnum=a.attnum
 where n.nspname in {S} and c.relkind in ('r','p') order by 1,2,3""")
tabs = {}
for r in cols: tabs.setdefault((r["s"],r["t"]),[]).append(r["col"])
for (s,t),cs in tabs.items():
    w(f'create table if not exists "{s}"."{t}" (\n  ' + ",\n  ".join(cs) + "\n);")
# restricciones (no FK primero, FK después)
cons = q(f"""select format('alter table %I.%I add constraint %I %s;', n.nspname, c.relname, k.conname, pg_get_constraintdef(k.oid)) s, k.contype::text ty
 from pg_constraint k join pg_class c on c.oid=k.conrelid join pg_namespace n on n.oid=c.relnamespace where n.nspname in {S} and k.contype in ('p','u','c','f','x') order by (k.contype='f'), (k.contype<>'p'), 1""")
for r in cons: w(r["s"])
# secuencias: dueño
for r in q(f"""select format('alter sequence %I.%I owned by %I.%I.%I;', sn.nspname, s.relname, tn.nspname, t.relname, a.attname) s
 from pg_depend d join pg_class s on s.oid=d.objid and s.relkind='S' join pg_namespace sn on sn.oid=s.relnamespace
 join pg_class t on t.oid=d.refobjid join pg_namespace tn on tn.oid=t.relnamespace join pg_attribute a on a.attrelid=t.oid and a.attnum=d.refobjsubid
 where d.deptype='a' and sn.nspname in {S}"""):
    w(r["s"])
# índices que no son de restricciones
for r in q(f"""select pg_get_indexdef(i.indexrelid)||';' s from pg_index i join pg_class c on c.oid=i.indrelid join pg_namespace n on n.oid=c.relnamespace
 where n.nspname in {S} and not exists (select 1 from pg_constraint k where k.conindid=i.indexrelid) order by 1"""):
    w(r["s"])
# funciones (sin las de extensiones)
for r in q(f"""select pg_get_functiondef(p.oid)||';' s from pg_proc p join pg_namespace n on n.oid=p.pronamespace
 where n.nspname in {S} and p.prokind in ('f','p') and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e') order by n.nspname, p.proname"""):
    w(r["s"])
# vistas en orden de oid (las dependientes se crean después)
for r in q(f"""select format('create or replace view %I.%I%s as %s', n.nspname, c.relname,
   case when c.reloptions is not null then ' with ('||array_to_string(c.reloptions,', ')||')' else '' end, pg_get_viewdef(c.oid)) s
 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in {S} and c.relkind='v' order by c.oid"""):
    w(r["s"])
# disparadores
for r in q(f"""select pg_get_triggerdef(t.oid)||';' s from pg_trigger t join pg_class c on c.oid=t.tgrelid join pg_namespace n on n.oid=c.relnamespace
 where n.nspname in {S} and not t.tgisinternal order by 1"""):
    w(r["s"])
# RLS
for r in q(f"""select format('alter table %I.%I enable row level security;', n.nspname, c.relname) || case when c.relforcerowsecurity then format(' alter table %I.%I force row level security;', n.nspname, c.relname) else '' end s
 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in {S} and c.relrowsecurity"""):
    w(r["s"])
pol = q("""select format('create policy %I on %I.%I as %s for %s to %s%s%s;', policyname, schemaname, tablename, permissive, cmd,
   array_to_string(roles, ', '), case when qual is not null then ' using ('||qual||')' else '' end,
   case when with_check is not null then ' with check ('||with_check||')' else '' end) s
 from pg_policies where schemaname in ('public','harvey','storage') order by schemaname, tablename, policyname""")
for r in pol: w(r["s"])
# permisos: tablas, vistas y secuencias
w("grant usage on schema harvey to anon, authenticated, service_role;" if q("select has_schema_privilege('authenticated','harvey','usage') x")[0]["x"] else "-- harvey: sin uso para authenticated")
for r in q(f"""select n.nspname s, c.relname t, c.relkind::text k, coalesce(array_to_string(c.relacl,','),'') acl
 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in {S} and c.relkind in ('r','p','v','S')"""):
    obj = ("sequence " if r["k"]=="S" else "table ") + f'"{r["s"]}"."{r["t"]}"'
    w(f"revoke all on {obj} from anon, authenticated, service_role;")
    for e in q(f"""select grantee::regrole::text g, string_agg(privilege_type, ', ') p from aclexplode((select relacl from pg_class where oid='"{r["s"]}"."{r["t"]}"'::regclass)) where grantee<>0 and grantee::regrole::text in ('anon','authenticated','service_role') group by 1""") if r["acl"] else []:
        w(f"grant {e['p']} on {obj} to {e['g']};")
# permisos de funciones
for r in q(f"""select format('%I.%I(%s)', n.nspname, p.proname, pg_get_function_identity_arguments(p.oid)) f, coalesce(array_to_string(p.proacl,','),'') acl, p.oid::text o
 from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname in {S} and p.prokind in ('f','p') and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e')"""):
    if not r["acl"]: continue
    w(f"revoke all on function {r['f']} from public, anon, authenticated, service_role;")
    for e in q(f"""select case when grantee=0 then 'public' else grantee::regrole::text end g from aclexplode((select proacl from pg_proc where oid={r['o']})) where privilege_type='EXECUTE' and (grantee=0 or grantee::regrole::text in ('anon','authenticated','service_role'))"""):
        w(f"grant execute on function {r['f']} to {e['g']};")
# carpetas de archivos
for r in q("""select format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %s, %s) on conflict (id) do nothing;', id, name, public::text, coalesce(file_size_limit::text,'null'), coalesce(quote_literal(allowed_mime_types::text)||'::text[]','null')) s from storage.buckets"""):
    w(r["s"])
# tareas de madrugada
for r in q("select format('select cron.schedule(%L, %L, %L);', jobname, schedule, command) s from cron.job"):
    w(r["s"])
import json; json.dump(out, open("sentencias.json","w")); open("esquema_completo.sql","w").write("\n".join(out)+"\n")
print(len(out), "sentencias")
